#Operators: = , += , -= , *= , /= , //= , %= , **=
#Task B3.1: Start with a variable score = 50. Apply each assignment operator one after another
#(in the order listed above), printing the value of score after every step
score = 50
print("Initial score:", score)
score += 15
print("After += 15:", score)
score -= 7
print("After -= 7:", score)
score *= 8
print("After *= 8:", score)
score /= 10
print("After /= 10:", score)
score %= 8
print("After %= 8:", score)

#output
#Initial score: 50
#After += 15: 65
#After -= 7: 58
#After *= 8: 464
#After /= 10: 46.4
#After %= 8: 6.399999999999999
