#Task B1.1: Take two integers a = 23 and b = 6. Write a program to compute and print the result of all
#seven arithmetic operators listed above on a and b.
a = 23
b = 6
print("addition:",a+b)
print("subtraction:",a-b)
print("multiplication:",a*b)
print("division:",a/b)
print("floor division:",a//b)
print("modulus:",a%b)
print("exponent:",a**b)

#output
#addition: 29
#subtraction: 17
#multiplication: 138
